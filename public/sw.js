/*
 * Service worker, который ничего не кеширует.
 *
 * Он здесь ровно для одного: без зарегистрированного обработчика `fetch`
 * Chrome не считает страницу устанавливаемой и не выдает `beforeinstallprompt`,
 * то есть предложить установку на Android нечем.
 *
 * Кеша нет намеренно. Офлайн-режим этой игре бессмыслен — без сервера
 * не работает ничего, — а лишний слой кеширования на приложении без сборщика
 * дает несвежий `app.js`: правку выкатили, а игрок неделю видит старую.
 * Обработчик ниже не зовет `respondWith`, поэтому запрос идет как обычно.
 */
self.addEventListener('install', () => {
  // Новая версия вступает в силу сразу, не дожидаясь закрытия старых вкладок:
  // ждать нечего, состояния воркер не хранит.
  void self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(self.clients.claim());
});

self.addEventListener('fetch', () => {
  // Пусто намеренно: сеть отвечает сама.
});
