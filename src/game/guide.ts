const percent = (share: number) => `${Math.round(share * 1000) / 10}%`;
const hours = (ms: number) => Math.round(ms / 3_600_000);
const num = (value: number) => Math.round(value).toLocaleString('ru-RU');

/** Длительность словами: «5 мин», «1 ч 20 мин», «2 сут 3 ч». */
function duration(seconds: number): string {
  const s = Math.max(0, Math.round(seconds));
  if (s < 60) return `${s} с`;
  const minutes = Math.round(s / 60);
  if (minutes < 60) return `${minutes} мин`;
  const h = Math.floor(minutes / 60);
  if (h < 24) return minutes % 60 ? `${h} ч ${minutes % 60} мин` : `${h} ч`;
  const days = Math.floor(h / 24);
  return h % 24 ? `${days} сут ${h % 24} ч` : `${days} сут`;
}

const p = (text: string): GuideBlock => ({ kind: 'p', text });
const list = (...items: string[]): GuideBlock => ({ kind: 'list', items });
const steps = (...items: string[]): GuideBlock => ({ kind: 'steps', items });
const tip = (text: string): GuideBlock => ({ kind: 'tip', text });
const table = (head: string[], rows: string[][]): GuideBlock => ({ kind: 'table', head, rows });

/** Сроки полетов считаются настоящим расчетом маршрута, без технологий. */
function flightTable(): GuideBlock {
  const one = (type: 'SMALL_CARGO' | 'PROBE' | 'RECYCLER') => ({ ...emptyShipCounts(), [type]: 1 });
  const home = { galaxyX: 0, galaxyY: 0 };
  const inSystem = (orbits: number, type: 'SMALL_CARGO' | 'PROBE' | 'RECYCLER') =>
    planFlight(one(type), emptyTechLevels(), { position: 1, system: home }, { position: 1 + orbits, system: home }).flightSeconds;
  const jump = (distance: number, type: 'SMALL_CARGO' | 'PROBE' | 'RECYCLER') =>
    planFlight(one(type), { ...emptyTechLevels(), HYPERDRIVE: 1 }, { position: 1, system: home }, {
      position: 1,
      system: { galaxyX: distance, galaxyY: 0 },
    }).flightSeconds;
  const row = (label: string, time: (type: 'SMALL_CARGO' | 'PROBE' | 'RECYCLER') => number) => [
    label,
    duration(time('SMALL_CARGO')),
    duration(time('RECYCLER')),
    duration(time('PROBE')),
  ];
  return table(
    ['Куда', shipLabel('SMALL_CARGO'), shipLabel('RECYCLER'), shipLabel('PROBE')],
    [
      row('Соседняя орбита', (type) => inSystem(1, type)),
      row('Через полсистемы', (type) => inSystem(7, type)),
      row('Через всю систему', (type) => inSystem(14, type)),
      row('Соседняя система (3 ед.)', (type) => jump(3, type)),
      row('10 ед. по карте', (type) => jump(10, type)),
      row('Край галактики (25 ед.)', (type) => jump(25, type)),
    ],
  );
}

